                ? trim((string) $this->input('start_date'))
                : null,

            'end_date' => $this->filled('end_date')
                ? trim((string) $this->input('end_date'))
                : null,

            /*
            |--------------------------------------------------------------------------
            | Termination
            |--------------------------------------------------------------------------
            */

