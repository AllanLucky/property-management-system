    /**
     * Configure additional validation after the standard rules.
     */
    public function withValidator($validator): void
    {
        $validator->after(function ($validator): void {
            /*
            |--------------------------------------------------------------------------
            | Resolve Existing Lease
            |--------------------------------------------------------------------------
            |
            | The route should normally be:
            |
            | PUT/PATCH /api/leases/{lease}
            |
            | We use route('lease') first and fall back to route('id') to
            | support either route naming convention.
            |
            */

            $lease = $this->route('lease') ?? $this->route('id');

            if (!$lease instanceof Lease) {
                return;
            }

            /*
            |--------------------------------------------------------------------------
            | Resolve Effective Dates
            |--------------------------------------------------------------------------
            |
            | If a date is not included in the request, use the existing
            | database value.
            |
            */

            $effectiveStartDate = $this->exists('start_date')
                ? $this->input('start_date')
                : $lease->start_date;

            $effectiveEndDate = $this->exists('end_date')
                ? $this->input('end_date')
                : $lease->end_date;

            /*
            |--------------------------------------------------------------------------
            | Validate Date Range
            |--------------------------------------------------------------------------
            */

            if (
                filled($effectiveStartDate) &&
                filled($effectiveEndDate)
            ) {
                try {
                    $startDate = Carbon::parse($effectiveStartDate)
                        ->startOfDay();

                    $endDate = Carbon::parse($effectiveEndDate)
                        ->startOfDay();

                    if ($endDate->lt($startDate)) {
                        $validator->errors()->add(
                            'end_date',
                            'The lease end date must be on or after the start date.'
                        );
                    }
                } catch (\Throwable) {
                    /*
                     * The standard date validation rules handle invalid
                     * date formats.
                     */
                }
            }

            /*
            |--------------------------------------------------------------------------
            | Fixed-Term Lease Validation
            |--------------------------------------------------------------------------
            |
            | If the lease is or becomes fixed-term, it must have an end date.
            |
            */

            $effectiveLeaseType = $this->filled('lease_type')
                ? $this->input('lease_type')
                : $lease->lease_type;

            if (
                $effectiveLeaseType === Lease::TYPE_FIXED_TERM &&
                blank($effectiveEndDate)
            ) {
                $validator->errors()->add(
                    'end_date',
                    'The end date is required for a fixed-term lease.'
                );
            }

            /*
            |--------------------------------------------------------------------------
            | Active Lease Validation
            |--------------------------------------------------------------------------
            |
            | An active lease cannot be changed to an end date that has
            | already passed.
            |
            | An end date equal to today is still valid. The lease expires
            | automatically from the following day.
            |
            */

            $effectiveStatus = $this->filled('status')
                ? $this->input('status')
                : $lease->status;

            if (
                $effectiveStatus === Lease::STATUS_ACTIVE &&
                filled($effectiveEndDate)
            ) {
                try {
                    $endDate = Carbon::parse($effectiveEndDate)
                        ->startOfDay();

                    if ($endDate->lt(today())) {
                        $validator->errors()->add(
                            'end_date',
                            'An active lease cannot have an end date in the past.'
                        );
                    }
                } catch (\Throwable) {
                    // Standard date validation handles invalid dates.
                }
            }

            /*
            |--------------------------------------------------------------------------
            | Expired Lease Validation
            |--------------------------------------------------------------------------
            |
            | A lease can only be explicitly changed to expired when its
            | end date has already passed.
            |
            */

            if (
                $effectiveStatus === Lease::STATUS_EXPIRED &&
                filled($effectiveEndDate)
            ) {
                try {
                    $endDate = Carbon::parse($effectiveEndDate)
                        ->startOfDay();

                    if ($endDate->gte(today())) {
                        $validator->errors()->add(
                            'status',
                            'A lease can only be marked as expired after its end date has passed.'
                        );
                    }
                } catch (\Throwable) {
                    // Standard date validation handles invalid dates.
                }
            }

            /*
            |--------------------------------------------------------------------------
            | Termination Validation
            |--------------------------------------------------------------------------
            */

            if (
                $effectiveStatus === Lease::STATUS_TERMINATED &&
                blank($this->input('termination_reason')) &&
                blank($lease->termination_reason)
            ) {
                $validator->errors()->add(
                    'termination_reason',
                    'A termination reason is required when terminating a lease.'
                );
            }

            /*
            |--------------------------------------------------------------------------
            | Cancellation Validation
            |--------------------------------------------------------------------------
            */

            if (
                $effectiveStatus === Lease::STATUS_CANCELLED &&
                blank($this->input('termination_reason')) &&
                blank($lease->termination_reason)
            ) {
                $validator->errors()->add(
                    'termination_reason',
                    'A cancellation reason is required when cancelling a lease.'
                );
            }
        });
    }

